"""Regenerate tokens.py from token_types.yaml. Run after editing token_types.yaml."""
import yaml

with open("token_types.yaml") as f:
    types = yaml.safe_load(f)

with open("tokens.py", "w") as f:
    f.write("# GENERATED by gen_tokens.py — DO NOT EDIT BY HAND.\n")
    f.write("# Edit token_types.yaml and re-run the generator instead.\n\n")
    f.write(f"TOKEN_TYPES = {types!r}\n")
